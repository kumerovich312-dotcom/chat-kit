import { describe, expect, it } from "vitest";
import { dialNumber, fmtPhone, maskPhone, normalizePhone, phoneCodeOfCountry, phoneDigits, phoneSearchDigits, phoneTail, samePhone } from "../../src/core/phone.js";

// Проверки телефонов. Номера — вымышленные (нули), смысл каждого
// случая сохранён: какая приставка, какая длина, какой код страны.

describe("normalizePhone — единый вид +996…", () => {
  const cases: [string, string, string | null, string][] = [
    ["0555 00-00-01", "+996", "+996555000001", "местный номер Кыргызстана с 0"],
    ["555000001", "+996", "+996555000001", "9 цифр без приставки"],
    ["+996 555 000 001", "+996", "+996555000001", "с кодом — не меняется"],
    ["00996555000001", "+996", "+996555000001", "00 — выход за границу"],
    ["12345", "+996", null, "короткий — не номер"],
    ["", "+996", null, "пусто"],
    ["996 555 00 00 01", "+996", "+996555000001", "код страны без «+»"],
    ["+49 89 1000 00", "+996", "+4989100000", "номер с «+» — код компании не приписываем"],
    ["+7 701 000 00 01", "+996", "+77010000001", "номер другой страны с «+»"],
    ["0049 89 1000 00", "+996", "+4989100000", "00 — выход за границу (Германия)"],
    ["79160000001", "+996", "+79160000001", "11 цифр без «+» — международный (так присылает телефония)"],
    ["8 916 000-00-01", "+996", "+79160000001", "Россия по-местному в компании из Кыргызстана"],
    ["+0555 00-00-01", "+996", "+996555000001", "лишний «+» перед местным номером"],
    ["55500000", "+996", null, "8 цифр — не угадываем"],
    ["0555 00-00-01 мама", "+996", null, "с припиской"],
    ["+996 555 00-00-01 доб. 5", "+996", null, "добавочный не приклеивается к номеру"],
    ["8 701 000 00 01", "+7", "+77010000001", "Казахстан: 8 перед номером"],
    ["701 000 00 01", "+7", "+77010000001", "Казахстан: 10 цифр без 8"],
    ["+7 701 000 00 01", "+7", "+77010000001", "Казахстан: с кодом"],
    ["77010000001", "+7", "+77010000001", "Казахстан: код без «+»"],
    ["+8 701 000 00 01", "+7", "+77010000001", "Казахстан: «+8» вместо «+7»"],
    ["8 (916) 000-00-01", "+7", "+79160000001", "Россия: 8 перед номером"],
    ["916 000 00 01", "+7", "+79160000001", "Россия: без 8"],
    ["8 10 996 555 00 00 01", "+7", "+996555000001", "8 10 — выход за границу"],
    ["0555 00-00-01", "+7", null, "номер Кыргызстана по-местному в Казахстане не угадываем"],
    ["8 029 000-00-01", "+375", "+375290000001", "Беларусь: 8 0 перед номером"],
    ["(029) 000-00-01", "+375", "+375290000001", "Беларусь: 0 перед номером"],
    ["29 000 00 01", "+375", "+375290000001", "Беларусь: без приставки"],
    ["90 000 00 01", "+998", "+998900000001", "Узбекистан"],
    ["8 90 000 00 01", "+998", "+998900000001", "Узбекистан: 8 по старой привычке"],
    ["99 800 00 01", "+998", "+998998000001", "Узбекистан: номер на 99 8… — не код страны"],
    ["091 00 00 01", "+374", "+37491000001", "Армения: 8 цифр после кода"],
    ["0532 000 00 01", "+90", "+905320000001", "Турция"],
    ["04 000 0001", "+971", "+97140000001", "ОАЭ: городской"],
    ["0151 00000001", "+49", "+4915100000001", "Германия: с 0"],
    ["+996 (0555) 00-00-01", "+996", "+996555000001", "0 межгорода после кода страны"],
    ["+375 (029) 000-00-01", "+996", "+375290000001", "Беларусь «+375 (029)» в компании из Кыргызстана"],
    ["+49 (0) 151 00000001", "+996", "+4915100000001", "Германия «+49 (0) 151»"],
    ["996 0555 00 00 01", "+996", "+996555000001", "код без «+» и 0 после него"],
  ];
  for (const [input, code, want, why] of cases) {
    it(`${why}: «${input}» → ${want ?? "как записан"}`, () => {
      expect(normalizePhone(input, code)).toBe(want);
    });
  }

  it("местный номер (с 0) каждой страны из списка узнаётся", () => {
    const national: [string, string][] = [
      ["+996", "555000001"], ["+7", "7010000001"], ["+998", "900000001"], ["+992", "900000001"], ["+375", "290000001"],
      ["+374", "91000001"], ["+995", "555000001"], ["+381", "640000001"], ["+48", "500000001"], ["+49", "15100000001"],
      ["+420", "600000001"], ["+90", "5320000001"], ["+971", "500000001"],
    ];
    const off = national.filter(([code, nat]) => normalizePhone("0" + nat, code) !== code + nat);
    expect(off).toEqual([]);
  });

  it("только цифры и последние 9 цифр", () => {
    expect(phoneDigits("+996 (555) 00-00-01")).toBe("996555000001");
    expect(phoneTail("0555 00-00-01")).toBe(phoneTail("+996 555 000 001"));
  });

  it("код страны по стране из настроек компании (KG)", () => {
    expect(phoneCodeOfCountry("KG")).toBe("+996");
    expect(phoneCodeOfCountry("kz")).toBe("+7");
    expect(phoneCodeOfCountry("HR")).toBe("");
    expect(phoneCodeOfCountry(null)).toBe("");
  });
});

describe("samePhone — один ли это номер", () => {
  it("разные записи одного номера — один номер", () => {
    expect(samePhone("0555 00-00-01", "+996 555 000 001", "+996")).toBe(true);
    expect(samePhone("8 701 000 00 01", "+77010000001", "+7")).toBe(true);
  });
  it("Казахстан и Россия с одинаковыми 9 последними цифрами — разные люди", () => {
    expect(phoneTail("+77010000001")).toBe(phoneTail("+79010000001"));
    expect(samePhone("+7 701 000 00 01", "+7 901 000 00 01")).toBe(false);
  });
  it("номер с припиской сравнивается по 9 последним цифрам", () => {
    expect(samePhone("0555 00-00-01 мама", "+996555000001", "+996")).toBe(true);
  });
  it("короткие номера не совпадают", () => {
    expect(samePhone("12345", "12345")).toBe(false);
  });
});

describe("phoneSearchDigits — поиск по части номера", () => {
  const finds: [string, string, string][] = [
    ["0555 00", "+996", "55500"],
    ["+996 555", "+996", "996555"],
    ["00996 555", "+996", "996555"],
    ["8 701 00", "+7", "70100"],
    ["+7 701", "+7", "7701"],
    ["8 029 00", "+375", "2900"],
    ["8 916 00", "+996", "91600"],
    ["+375 (029) 00", "+996", "3752900"],
  ];
  for (const [input, code, want] of finds) {
    it(`«${input}» → ${want}`, () => expect(phoneSearchDigits(input, code)).toBe(want));
  }
});

describe("fmtPhone — показ по-местному", () => {
  const shows: [string | null, string, string, string][] = [
    ["+996550000014", "+996", "+996 550 00-00-14", "сохранённый номер Кыргызстана"],
    ["+996 555 00-00-01", "+996", "+996 555 00-00-01", "уже в нужном виде — не меняется"],
    ["0555 00-00-01", "+996", "+996 555 00-00-01", "местный номер из импорта — с кодом компании"],
    ["+996 312 00-00-30", "+996", "+996 312 00-00-30", "городской номер"],
    ["+77010000001", "+7", "+7 701 000-00-01", "Казахстан"],
    ["+7 (916) 000 00 01", "+7", "+7 916 000-00-01", "Россия, скобки и пробелы"],
    ["+77010000001", "+996", "+7 701 000-00-01", "номер другой страны — по её правилам"],
    ["500 000 001", "+48", "+48 500 000 001", "контакт из Польши без кода"],
    ["+49 89 1000 00", "+996", "+49 89 1000 00", "Германия — как записан"],
    ["8 701 000 00 01", "+7", "+7 701 000-00-01", "Казахстан по-местному, с 8"],
    ["+87010000001", "+7", "+7 701 000-00-01", "номер, сохранённый с ошибкой «+8…»"],
    ["+971 4 000 00 15", "+996", "+971 4 000 00 15", "номер другой длины — как записан"],
    ["+996 555 00-00-01 доб. 5", "+996", "+996 555 00-00-01 доб. 5", "приписка к номеру не теряется"],
    ["12345", "+996", "12345", "не номер — как записан"],
    [null, "+996", "", "нет номера"],
  ];
  for (const [input, code, want, why] of shows) {
    it(`${why} — ${want || "пусто"}`, () => expect(fmtPhone(input, code)).toBe(want));
  }
  it("из показа снова получается тот же номер", () => {
    expect(normalizePhone(fmtPhone("+996550000014", "+996"), "+996")).toBe("+996550000014");
  });
});

describe("maskPhone и dialNumber", () => {
  it("скрытая середина: код, оператор и две последние цифры видны", () => {
    expect(maskPhone("+996550000011")).toBe("+996 550 ••-••-11");
    expect(maskPhone("+77010000067")).toBe("+7 701 •••-••-67");
    expect(maskPhone("0550000011", "+996")).toBe("+996 550 ••-••-11");
    expect(maskPhone("")).toBeNull();
    expect(maskPhone("12-34")).toBeNull();
  });
  it("номер для набора", () => {
    expect(dialNumber("+996555000001", "+996")).toBe("+996555000001");
    expect(dialNumber("0555 00-00-01", "+996")).toBe("+996555000001");
    expect(dialNumber("0555 00-00-01 мама", "+996")).toBe("+996555000001");
    expect(dialNumber("", "+996")).toBe("");
  });
});
